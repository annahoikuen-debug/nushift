"""``importers._age_years`` の回帰テスト（R1-D）。

**何を、どこで壊していたか**

園業務支援システムの年齢欄は ``3歳6ヶ月`` のように年と月の両方を書く。
旧実装は数字を全部つなげて ``36`` にしてから月表記だと判定していたため、
**年を持つ表記をすべて 0 歳児に落としていた**::

    "3歳6ヶ月"  -> "0"   （正しくは "3"）
    "4歳2か月"  -> "0"   （正しくは "4"）
    "2歳11ヶ月" -> "0"   （正しくは "2"）

0 歳児は要人員が最も大きい区分（``0歳児4:1``）なので、
取り込みのたびに必要人員が過剰になり、シフトが「配置基準未達」になる。
静かに違う数字を出すため発見しづらい。

以下の各ケースは **すべて明示的に期待値を固定する**。
"""

from __future__ import annotations

from typing import Any

import pytest

from shiftai.importers import _age_years

#: 現場であり得る表記 → 期待する年齢区分。
#: ``0``〜``5`` に収める（5 歳以上は 5 に丸める既存の方針を維持）。
CASES: list[tuple[Any, str]] = [
    # --- 今回のバグの中心: 年 + 月 の両方が書く表記 ---
    ("3歳6ヶ月", "3"),
    ("4歳2か月", "4"),
    ("2歳11ヶ月", "2"),
    ("1歳0ヶ月", "1"),
    ("5歳0ヶ月", "5"),
    ("4才6ヶ月", "4"),  # 「才」の表記
    # --- 年のみの表記 ---
    ("3歳", "3"),
    ("3才", "3"),
    ("0歳", "0"),
    ("5歳", "5"),
    # --- 月のみの表記（年が無いので 0 歳） ---
    ("11ヶ月", "0"),
    ("6ヶ月", "0"),
    ("11か月", "0"),
    ("11カ月", "0"),
    # --- 数字のみ ---
    ("3", "3"),
    (3, "3"),
    ("0", "0"),
    (5, "5"),
    # --- クランプ（5 歳以上は 5） ---
    ("6歳", "5"),
    ("7歳", "5"),
    ("100", "5"),
    # --- 全角 / NFKC 正規化 ---
    ("１歳", "1"),
    ("０歳", "0"),
    ("５歳", "5"),
    ("3歳６ヶ月", "3"),
    # --- 解釈不能・空 ---
    (None, "0"),
    ("", "0"),
    ("  ", "0"),
    ("不明", "0"),
    ("-", "0"),
    # --- 負の値は 0 に丸める（1 にしない） ---
    ("-1", "0"),
    ("-3歳", "0"),
]


@pytest.mark.parametrize(("value", "expected"), CASES)
def test_年齢表記を年齢区分に落とす(value: Any, expected: str) -> None:
    assert _age_years(value) == expected


@pytest.mark.parametrize(
    "value",
    ["3歳6ヶ月", "4歳2か月", "2歳11ヶ月", "1歳0ヶ月", "5歳0ヶ月", "4才6ヶ月"],
)
def test_年を持つ表記が0歳児にならない(value: str) -> None:
    """**回帰の中心**。年があれば 0 歳児にしないこと。

    「全是 0 歳児」になると必要人員が全部 0 歳児の比率で計算され、
    配置基準を満たさない解しか出なくなる。
    """
    assert _age_years(value) != "0", f"{value!r} が 0 歳児に落とされた"


def test_結果は必ず0から5の範囲になる() -> None:
    """出力は常に 0〜5 の文字列であること（区分外値は丸める）。"""
    for value in ("-5", "99", "999", "百", float("nan"), None, "0歳0ヶ月"):
        got = _age_years(value)
        assert got in {"0", "1", "2", "3", "4", "5"}, f"{value!r} -> {got!r}"


def test_月の有無で年の判定が変わらない() -> None:
    """同じ年の表記は、月：有る無しで結果が変わらないこと。"""
    for year in range(6):
        without = _age_years(f"{year}歳")
        for month_text in ("", "0ヶ月", "6ヶ月", "11か月"):
            with_month = _age_years(f"{year}歳{month_text}")
            assert with_month == without, (
                f"{year}歳{month_text!r} -> {with_month} が {without} と違う"
            )


