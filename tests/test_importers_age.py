# float64 推論の回帰（Round 2 で発見）
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        (0.0, "0"),
        (1.0, "1"),
        (2.0, "2"),
        (3.0, "3"),
        (4.0, "4"),
        (5.0, "5"),
        (6.0, "5"),
        (3.5, "3"),
        (2.5, "2"),
        (-1.0, "0"),
        (float("nan"), "0"),
        (1, "1"),
        (3, "3"),
    ],
)
def test_float64の年齢は小数点を切り捨てる(value: Any, expected: str) -> None:
    """``float`` の年齢は整数部を採用すること。

    **なぜ重要か**: ``pandas`` は年齢列に空欄が 1 つでもあれば
    **float64** として推論する（``pd.read_excel`` / ``pd.read_csv`` の既定）。
    Round 1 の修正は文字列表現だけを見ていたため、
    ``3.0`` → ``"3.0"`` → 数字だけ取り出すと ``"30"`` → **5 歳**になっていた。
    5 歳は定員比が最も低い区分なので、必要人員が **過少に算出**され、
    配置基準を満たさないシフトが「求出できた」と出てしまう。
    """
    assert _age_years(value) == expected


def test_空欄つきのExcel相当の推論でも年齢が狂わない(tmp_path) -> None:
    """空欄を含む年齢列を float64 として読み込んでも年纪が保たれること。

    実際の ``pd.read_csv`` / ``pd.read_excel`` の推論を再現する。
    """
    import pandas as pd

    csv = tmp_path / "children.csv"
    csv.write_text(
        "園児ID,氏名,生年月日,年齢\n"
        "C001,園児A,2023-04-01,3\n"
        "C002,園児B,2022-04-01,4\n"
        "C003,園児C,2021-04-01,\n",  # 空欄 → 列全体が float64 になる
        encoding="utf-8",
    )
    frame = pd.read_csv(csv)
    ages = [row["年齢"] for _, row in frame.iterrows()]
    assert any(isinstance(a, float) for a in ages), (
        f"検証前提: 空欄があるため年齢列が float64 になっている（実際: {ages}）"
    )
    got = [_age_years(a) for a in ages]
    assert got == ["3", "4", "0"], (
        f"float64 推論で年齢が狂った: {list(zip(ages, got, strict=False))}"
    )
